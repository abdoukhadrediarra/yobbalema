def psql(script, db=DB, user_uid=None, role="authenticated", check=False):
    pre = ""
    if role:
        pre += f"set role {role};\n"
    if user_uid:
        pre += f"select set_config('request.jwt.claim.sub','{user_uid}',false) \\gset\n"
    p = subprocess.run(["su", "postgres", "-c", f"psql -d {db} -At -q -v ON_ERROR_STOP=1"],
                       input=pre + script, capture_output=True, text=True)
    return p.returncode, p.stdout.strip(), p.stderr.strip()

def admin(script):
    rc, out, err = psql(script, role=None)
    if rc != 0:
        print("ADMIN SQL ERROR:", err); sys.exit(1)
    return out

def ok(name, cond, detail=""):
    global PASS, FAIL
    if cond: PASS += 1; print(f"  PASS  {name}")
    else: FAIL += 1; print(f"  FAIL  {name}  {detail}")

def expect_ok(name, uid, sql):
    rc, out, err = psql(sql, user_uid=uid)
    ok(name, rc == 0, err[:300])
    return out

def expect_err(name, uid, sql, contains):
    rc, out, err = psql(sql, user_uid=uid)
    ok(name, rc != 0 and contains in err, f"(rc={rc}) {err[:300]}")


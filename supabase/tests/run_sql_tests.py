def pay_status(ref_id):
    return admin(f"select string_agg(statut_transaction, ',' order by categorie_montant) from payments where source_id='{ref_id}'")
def new_intent(uid, source, sid, prov="wave"):
    rc, out, err = psql(f"select id||'|'||ref_courte||'|'||montant||'|'||statut from demander_paiement('{source}','{sid}','{prov}')", user_uid=uid)
    return (out.split("|") if rc == 0 else None), err
def confirm(ref, statut, montant="null", pref="null", detail="null"):
    q = lambda v: v if v == "null" else f"'{v}'"
    return admin(f"select statut||'|'||coalesce(detail,'') from confirmer_intent('{ref}','{statut}',{montant},{q(pref)},{q(detail)})")

